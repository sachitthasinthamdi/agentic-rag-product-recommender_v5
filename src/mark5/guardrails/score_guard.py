"""ปฏิเสธคำค้นที่ไม่มีของตรงในคลัง (negative rejection) โดยดูคะแนนความใกล้เคียง

**ที่มาของแนวคิด:** RGB benchmark (Chen et al., AAAI 2024) ระบุว่า *negative rejection*
เป็น 1 ใน 4 ความสามารถพื้นฐานของระบบ RAG และ LLM ทั่วไปทำได้แย่ — mark4 ตอบ "ไม่พบ"
0 ครั้งจาก 25 คำค้น คือเสนอของเสมอแม้ไม่มีของตรง

**ทำไมใช้คะแนนดิบ ไม่ใช้ LLM:** ตรวจสอบแล้วว่า LLM judge บนเครื่องนี้เชื่อถือไม่ได้
(κ = 0.246 ดู `docs/02_judge_reliability.md`) เกณฑ์ที่คำนวณจากตัวเลขตรง ๆ จึงวัดผลได้
โดยไม่ต้องพึ่งสิ่งที่พิสูจน์แล้วว่าไม่น่าเชื่อถือ

**ข้อมูลที่ใช้ตั้งเกณฑ์** (วัดจากคำค้นจริง 25 คำ เทียบคำค้นนอกขอบเขต 15 คำ บนดัชนีเต็ม):

| สัญญาณ | คำค้นที่มีของจริง | คำค้นนอกขอบเขต |
|---|---|---|
| คะแนนอันดับ 1 | ต่ำสุด 0.529 · มัธยฐาน 0.716 | สูงสุด 0.580 · มัธยฐาน 0.495 |
| คะแนนเฉลี่ย 5 อันดับแรก | ต่ำสุด 0.513 · มัธยฐาน 0.696 | สูงสุด 0.542 |

สองกลุ่มซ้อนกันแค่ช่วงแคบ ๆ จึงตั้งเกณฑ์แยกได้
**ส่วน "ระยะห่างอันดับ 1 ถึง 5" ใช้ไม่ได้** — สองกลุ่มซ้อนกัน 14/15 (ทดลองแล้วทิ้ง)
"""

from __future__ import annotations

from dataclasses import dataclass

# ค่าตั้งต้น: ปรับเทียบจากครึ่งหนึ่งของชุดคำค้น (ดู eval/pilot/eval_guardrails.py)
# อยู่กลางช่วงที่สองกลุ่มซ้อนกัน (0.529–0.580) ค่อนไปทางที่ยอมรับของจริงไว้ก่อน
# เพราะปฏิเสธคำค้นที่มีของจริง (false rejection) เสียหายกว่าเสนอของที่ไม่ค่อยตรง
DEFAULT_MIN_TOP1 = 0.55
DEFAULT_MIN_MEAN5 = 0.52


@dataclass
class RejectionDecision:
    rejected: bool
    reason: str
    top1: float
    mean_top5: float


def evaluate(scores: list[float],
             min_top1: float = DEFAULT_MIN_TOP1,
             min_mean5: float = DEFAULT_MIN_MEAN5) -> RejectionDecision:
    """ตัดสินว่าควรตอบ "ไม่พบสินค้าที่ตรง" หรือไม่ จากคะแนนของผลการค้น

    ใช้ทั้งสองเกณฑ์แบบ **และ** — ต้องผ่านทั้งคู่จึงจะไม่ถูกปฏิเสธ
    เกณฑ์อันดับ 1 จับกรณี "ไม่มีอะไรใกล้เคียงเลย" ส่วนเกณฑ์ค่าเฉลี่ย 5 อันดับแรก
    จับกรณี "มีของบังเอิญใกล้อยู่ชิ้นเดียว ที่เหลือไม่เกี่ยว" ซึ่งก็ไม่ควรเสนอเหมือนกัน
    """
    if not scores:
        return RejectionDecision(True, "ไม่มีผลการค้นเลย", 0.0, 0.0)

    top1 = scores[0]
    mean5 = sum(scores[:5]) / min(len(scores), 5)

    if top1 < min_top1:
        return RejectionDecision(
            True, f"คะแนนอันดับ 1 ({top1:.3f}) ต่ำกว่าเกณฑ์ {min_top1}", top1, mean5)
    if mean5 < min_mean5:
        return RejectionDecision(
            True, f"คะแนนเฉลี่ย 5 อันดับแรก ({mean5:.3f}) ต่ำกว่าเกณฑ์ {min_mean5}", top1, mean5)

    return RejectionDecision(False, "ผ่านเกณฑ์คะแนน", top1, mean5)
